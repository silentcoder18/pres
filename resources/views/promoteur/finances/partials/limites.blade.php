     A reprendre quand la finance (etape 5) arrivera sur le serveur. --}}
<ul>
    <li>
        <strong>Commissions prévues et commissions dues.</strong>
        Les commissions prévues sont celles des articles des commandes déposées dans la semaine : une prévision, faite dès le dépôt.
        Les commissions dues, données dans « Charges de l'atelier », sont celles des tâches terminées dans la semaine.
    </li>
    <li>
        <strong>Solde prévisionnel.</strong>
        Il compare la recette de la semaine aux commissions prévues, site par site.
        Il ne déduit pas encore les charges réelles de l'atelier (commissions dues et consommables) : leur répartition entre les sites viendra avec la clôture hebdomadaire.
    </li>
    <li>
        <strong>Emprunts et réserve.</strong>
        Un recouvrement tardif doit d'abord rembourser l'emprunt de la semaine d'origine de la commande.
        Les emprunts ne sont pas encore tenus ici (étape 5) : pour l'instant, tout recouvrement tardif est affecté à la réserve.
    </li>
    <li>
        <strong>Paiement des commissions et clôture hebdomadaire.</strong>
        Ils ne se font pas encore ici (étape 5) : ce rapport ne clôture aucune semaine.
    </li>
    <li>
        <strong>Sommes rendues aux clients.</strong>
        L'avance rendue au client après l'annulation de sa commande est retirée de la semaine où elle avait été reçue :
        la recette d'une semaine passée peut donc baisser après coup.
        Le trop-perçu rendu à un client dont la facture a baissé après une correction est retiré, lui, de la semaine où il est rendu.
        Les comptes de journée et les caisses déduisent l'un et l'autre le jour où ils sortent de la caisse.
    </li>
    <li>
        <strong>Sites hors ligne.</strong>
        Seul ce que les postes ont synchronisé est compté : un site hors ligne n'est à jour qu'après sa prochaine synchronisation.
    </li>
</ul>
